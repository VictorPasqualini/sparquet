/**
 * Icon registry for the catalog.
 *
 * Catalog entries name their icon as a string (`icon: 'Filter'`) so the catalog
 * stays free of React imports. This module is the only place that turns those
 * names back into components. The import list is explicit — a dynamic
 * `lucide-react/dist/esm/icons/${name}` import would defeat tree-shaking and ship
 * the whole icon set.
 */

